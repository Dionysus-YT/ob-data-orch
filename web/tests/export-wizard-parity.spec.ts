import { expect, test, type Page } from '@playwright/test'
import { DATA_SOURCE_UI_FIXTURES } from '../src/workbench/sources/dataSourceUiFixture'
import type { ExportDraftInput } from '../src/api/browser'

async function mockExport(page: Page, singleNode = false) {
  let draft: ExportDraftInput | undefined, revision = 1, nodeName = '合成执行节点'
  const requests: string[] = []
  const envelope = () => ({ item: { ...draft, id: 'synthetic-draft', revision, configFingerprint: 'a'.repeat(64), capabilityVersion: draft?.draftState === 'EDITING' ? 'export-draft-edit-v1' : 'export-odp-single-table-csv-v1', config: { draftState: draft?.draftState, config: draft?.config } } })
  await page.route('**/api/v1/**', async route => {
    const request = route.request(), path = new URL(request.url()).pathname
    requests.push(request.method() + ' ' + path)
    if (path === '/api/v1/data-sources') return route.fulfill({ json: { items: DATA_SOURCE_UI_FIXTURES } })
    if (path === '/api/v1/execution-nodes') return route.fulfill({ json: { items: [{ id: 'synthetic-node', displayName: nodeName, platform: 'WINDOWS_AMD64' }, ...(singleNode ? [] : [{ id: 'synthetic-node-2', displayName: '合成备用节点', platform: 'WINDOWS_AMD64' }])] } })
    if (path === '/api/v1/export-drafts' && request.method() === 'POST') { draft = request.postDataJSON(); return route.fulfill({ status: 201, json: { id: 'synthetic-draft' } }) }
    if (path === '/api/v1/export-drafts/synthetic-draft') {
      if (request.method() === 'PATCH') { draft = request.postDataJSON(); revision++ }
      return route.fulfill({ json: envelope() })
    }
    if (path.endsWith(':preview-command')) return route.fulfill({ json: { command: 'obdumper --csv -p ******', configFingerprint: 'a'.repeat(64) } })
    if (path.endsWith(':precheck')) return route.fulfill({ status: 202, json: { id: 'synthetic-check' } })
    if (path === '/api/v1/prechecks/synthetic-check') return route.fulfill({ json: { item: { id: 'synthetic-check', draftId: 'synthetic-draft', draftRevision: revision, nodeId: draft?.nodeId, configFingerprint: 'a'.repeat(64), status: 'FAILED', integrityStatus: 'COMPLETE', validUntil: '2099-01-01T00:00:00Z', results: [] } } })
    return route.fulfill({ json: { items: [] } })
  })
  return { requests, draft: () => draft, rename: () => { nodeName = '合成节点（已更名）' } }
}

async function step(page: Page, index: number) {
  if (index === 1) await page.locator('.wizard-ant-step-rail .ant-steps-item').first().click()
  else {
    await page.getByRole('button', { name: '全部参数', exact: true }).click()
    const catalog = page.getByRole('dialog', { name: '导出全部参数' })
    await catalog.getByRole('textbox').fill(index === 2 ? 'database' : 'file-path')
    await catalog.getByRole('button', { name: index === 2 ? '导出内容与对象' : '执行与输出', exact: true }).first().click()
  }
  await expect(page).toHaveURL(new RegExp('step=' + index))
}
async function node(page: Page, name = '合成执行节点 · Windows · x86_64') {
  await page.locator('.export-node-select .ant-select').click()
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option-content').getByText(name, { exact: true }).click()
}

test('参数目录重复关闭返回触发器，跳到输出步骤不把空配置标为完成', async ({ page }) => {
  await mockExport(page)
  await page.goto('/exports/new')
  const trigger = page.getByRole('button', { name: '全部参数', exact: true })
  for (let cycle = 0; cycle < 2; cycle++) {
    await trigger.focus(); await page.keyboard.press('Enter')
    await expect(page.getByRole('dialog', { name: '导出全部参数' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
  }
  await step(page, 4)
  await expect(page.locator('.wizard-ant-step-rail .ant-steps-item-finish')).toHaveCount(0)
  await expect(page.getByText('待完善', { exact: true })).toHaveCount(3)
})

test('两类参数抽屉在展开动画中关闭与立即重开，也释放背景并返回本次入口', async ({ page }) => {
  await mockExport(page)
  for (const [url, title] of [['/exports/new', '导出全部参数'], ['/imports/normal/new', '普通导入全部参数']]) {
    await page.goto(url!)
    const trigger = page.getByRole('button', { name: '全部参数', exact: true })
    const dialog = page.getByRole('dialog', { name: title!, exact: true })
    for (let cycle = 0; cycle < 5; cycle++) {
      await trigger.focus(); await page.keyboard.press('Enter')
      await expect(dialog).toBeVisible()
      await page.keyboard.press('Escape')
      await expect(trigger).toBeFocused()
      expect(await page.locator('#app').evaluate(element => element.hasAttribute('inert'))).toBe(false)
    }
    await expect(dialog).not.toBeVisible()
  }
})

test('干净草稿离开不确认，更换来源的取消保留当前选择与内容', async ({ page }) => {
  await mockExport(page)
  await page.goto('/exports/new')
  const radios = page.getByRole('radio')
  await radios.first().check()
  await page.getByRole('button', { name: '下一步：导出内容与对象', exact: true }).click()
  await page.getByRole('radiogroup', { name: '导出内容', exact: true }).getByText('仅导出数据', { exact: true }).click()
  await step(page, 1)
  await radios.nth(1).click()
  const confirm = page.getByRole('dialog', { name: '更换导出数据源？' })
  await expect(confirm).toBeVisible()
  await expect(confirm.getByRole('button', { name: '保留当前配置', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(confirm).not.toBeVisible()
  await expect(radios.first()).toBeChecked()
  await page.getByRole('button', { name: '下一步：导出内容与对象', exact: true }).click()
  await expect(page.getByRole('radio', { name: '仅导出数据', exact: true })).toBeChecked()
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByText('草稿已保存', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '普通导入', exact: true }).click()
  await expect(page.getByRole('heading', { name: '新建普通导入任务', exact: true })).toBeVisible()
  await expect(page.getByRole('dialog', { name: '离开导出配置？' })).toHaveCount(0)
})

