test('两步节点选择使用同一状态，刷新名称保留选择且控件保持紧凑', async ({ page }, info) => {
  const api = await mockExport(page)
  await page.goto('/exports/new?step=2')
  await node(page)
  api.rename()
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await expect(page.locator('.export-node-select')).toContainText('合成节点（已更名） · Windows · x86_64')
  await step(page, 4)
  await expect(page.locator('.export-node-select')).toContainText('合成节点（已更名） · Windows · x86_64')
  await node(page, '合成备用节点 · Windows · x86_64')
  await step(page, 2)
  await expect(page.locator('.export-node-select')).toContainText('合成备用节点 · Windows · x86_64')
  const select = await page.locator('.export-node-select .ant-select').boundingBox()
  const refresh = await page.getByRole('button', { name: '刷新', exact: true }).boundingBox()
  expect(Math.abs(select!.y - refresh!.y)).toBeLessThan(2)
  expect(refresh!.x - (select!.x + select!.width)).toBeLessThan(13)
  await page.screenshot({ path: info.outputPath('export-node-select.png'), fullPage: false })
})
