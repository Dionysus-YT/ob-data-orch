test('服务端分页、筛选和迟到响应不会被 Table 状态重解释', async ({ page }) => {
  const urls: URL[] = []
  let releaseSlow: (() => void) | undefined
  await page.route('**/api/v1/data-sources?*', async route => {
    const url = new URL(route.request().url()); urls.push(url)
    const keyword = url.searchParams.get('keyword')
    if (keyword === 'slow') await new Promise<void>(resolve => { releaseSlow = resolve })
    await route.fulfill({ json: { items: [{ ...DATA_SOURCE_UI_FIXTURES[0], displayName: keyword || (url.searchParams.has('cursor') ? '第二页事实' : '首页事实') }], total: 20, nextCursor: url.searchParams.has('cursor') ? '' : 'synthetic-next' } })
  })
  await page.goto('/data-sources')
  await expect(page.getByRole('button', { name: '首页事实', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page.getByRole('button', { name: '第二页事实', exact: true })).toBeVisible()
  expect(urls.at(-1)?.searchParams.get('cursor')).toBe('synthetic-next')
  await page.getByRole('textbox', { name: '搜索数据源' }).fill('slow')
  await expect.poll(() => Boolean(releaseSlow)).toBe(true)
  await page.getByRole('textbox', { name: '搜索数据源' }).fill('latest')
  await expect(page.getByRole('button', { name: 'latest', exact: true })).toBeVisible()
  expect(urls.at(-1)?.searchParams.has('cursor')).toBe(false)
  releaseSlow!()
  await expect(page.getByRole('button', { name: 'slow', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'latest', exact: true })).toBeVisible()
})

test('删除安全确认与服务端并发资格复验，取消不发请求', async ({ page }) => {
  let deletes = 0
  let revision = ''
  const item = { ...DATA_SOURCE_UI_FIXTURES[0], displayName: '合成可删除数据源', lifecycleEligibility: { enable: { allowed: false }, disable: { allowed: true }, delete: { allowed: true }, archive: { allowed: false } } }
  await page.route('**/api/v1/**', route => {
    if (route.request().method() === 'DELETE') {
      deletes++; revision = route.request().headers()['if-match'] ?? ''
      return route.fulfill({ status: 409, json: { code: 'UNFINISHED_TASKS_EXIST' } })
    }
    return route.fulfill({ json: { items: [item], total: 1, nextCursor: '' } })
  })
  await page.goto('/data-sources')
  const trigger = page.getByRole('button', { name: '合成可删除数据源 的操作' })
  await trigger.click()
  await expect(page.getByRole('menuitem')).toHaveCount(2)
  await page.getByRole('menuitem', { name: '删除', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '删除数据源' })
  await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  expect(deletes).toBe(0)
  await trigger.click()
  await page.getByRole('menuitem', { name: '删除', exact: true }).click()
  await dialog.getByRole('button', { name: '删除', exact: true }).click()
  await expect.poll(() => deletes).toBe(1)
  expect(revision).toContain('101')
  await expect(page.getByRole('button', { name: '合成可删除数据源', exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('操作未完成')
})

