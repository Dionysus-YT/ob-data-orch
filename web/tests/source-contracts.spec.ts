test('加载、空结果与错误重试保持独立状态', async ({ page }) => {
  let release: (() => void) | undefined
  let attempts = 0
  await page.route('**/api/v1/data-sources?*', async route => {
    attempts++
    if (attempts === 1) {
      await new Promise<void>(resolve => { release = resolve })
      return route.fulfill({ status: 500, json: { code: 'INTERNAL_ERROR' } })
    }
    return route.fulfill({ json: { items: [], total: 0, nextCursor: '' } })
  })
  await page.goto('/data-sources')
  await expect(page.getByRole('status', { name: '正在加载数据源' })).toBeVisible()
  await expect(page.getByRole('button', { name: '刷新数据源', exact: true })).toBeDisabled()
  await expect(page.getByRole('heading', { name: '尚未创建数据源' })).toHaveCount(0)
  release!()
  await expect(page.getByRole('alert')).toContainText('暂时无法读取数据源')
  await page.getByRole('button', { name: '重新加载', exact: true }).click()
  await expect(page.getByRole('heading', { name: '尚未创建数据源' })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
})
